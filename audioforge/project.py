"""AudioProject manifest and filesystem helpers."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any


def posix_relative(root: Path, path: Path) -> str:
    return path.resolve().relative_to(root.resolve()).as_posix()


def create_layout(root: Path) -> Path:
    root.mkdir(parents=True, exist_ok=True)
    for name in ("source", "assets", "stems", "renders", "analysis", "metadata"):
        (root / name).mkdir(exist_ok=True)
    return root


def write_project(
    root: Path,
    *,
    title: str,
    kind: str,
    backend: dict[str, Any],
    inputs: dict[str, Any],
    tracks: list[dict[str, Any]],
    outputs: list[Path],
    brief: str,
    extra: dict[str, Any] | None = None,
) -> dict[str, Any]:
    create_layout(root)
    manifest: dict[str, Any] = {
        "version": "1",
        "title": title,
        "kind": kind,
        "backend": backend,
        "inputs": inputs,
        "tracks": tracks,
        "outputs": [posix_relative(root, output) for output in outputs],
        "events": [],
        "automation": [],
        "loop": None,
        "analysis": {},
    }
    if extra:
        manifest.update(extra)
    (root / "project.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    (root / "brief.md").write_text(brief.rstrip() + "\n", encoding="utf-8")
    (root / "README.md").write_text(
        f"# {title}\n\nGenerated by Audio Forge using the `{backend.get('name', 'unknown')}` backend.\n\n"
        "See `project.json` for the editable project manifest.\n",
        encoding="utf-8",
    )
    (root / "metadata" / "backend.json").write_text(
        json.dumps(backend, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    return manifest


def write_source_json(root: Path, name: str, data: dict[str, Any]) -> Path:
    path = root / "source" / name
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return path
